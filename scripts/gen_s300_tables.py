#!/usr/bin/env python3
"""Generate YomiKit/Protocol/S300Tables.swift from SANE epjitsu sources.

Usage: gen_s300_tables.py <epjitsu.c> <epjitsu-cmd.h> <out.swift>
"""
import re
import sys

src_c, src_h, out_path = sys.argv[1:]
header = open(src_h).read()
source = open(src_c).read()

arrays = {}
for name, body in re.findall(r"static unsigned char (\w+)\[\]\s*=\s*\{(.*?)\};", header, re.S):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    arrays[name] = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", body)]

row_re = re.compile(
    r"\{\s*MODEL_S300,\s*MODE_COLOR,\s*(\d+),\s*(\d+),\s*(\d),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),"
    r"\s*([\d*]+),\s*([\d*]+),\s*(\d+),\s*(\d+),\s*([\d*]+),\s*([\d*]+),\s*(\d+),"
    r"\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+)\s*\}", re.S)

rows = []
for m in row_re.finditer(source):
    g = list(m.groups())
    nums = [eval(x) for x in g[:14]]
    rows.append((nums, g[14:]))

def swift_bytes(values):
    lines = []
    for i in range(0, len(values), 16):
        lines.append("            " + ", ".join(f"0x{v:02X}" for v in values[i:i + 16]) + ",")
    return "[\n" + "\n".join(lines) + "\n        ]"

out = ["// Generated by scripts/gen_s300_tables.py from SANE backend/epjitsu (GPL-2.0-or-later).",
       "// Values originate from USB captures of the vendor driver; do not edit by hand.",
       "",
       "extension S300Profile {",
       "    static let all: [S300Profile] = ["]
for nums, names in rows:
    xres, yres, usb, mxx, mnx, mxy, mny, lin_s, pln_s, pln_w, bh, cls, cps, cpw = nums
    out.append("        S300Profile(")
    out.append(f"            xResolution: {xres}, yResolution: {yres}, usbPower: {'true' if usb else 'false'},")
    out.append(f"            maxX: {mxx}, minX: {mnx}, maxY: {mxy}, minY: {mny},")
    out.append(f"            lineStride: {lin_s}, planeStride: {pln_s}, planeWidth: {pln_w}, blockHeight: {bh},")
    out.append(f"            calLineStride: {cls}, calPlaneStride: {cps}, calPlaneWidth: {cpw},")
    labels = ["coarseCalWindow", "fineCalWindow", "sendCalWindow", "sendCal1Header", "sendCal2Header", "scanWindow"]
    for label, name in zip(labels, names):
        out.append(f"            {label}: {swift_bytes(arrays[name])},")
    out[-1] = out[-1].rstrip(",")
    out.append("        ),")
out.append("    ]")
out.append("")
out.append(f"    static let coarseCalibration: [UInt8] = {swift_bytes(arrays['coarseCalData_S300'])}")
out.append("}")
open(out_path, "w").write("\n".join(out) + "\n")
print(f"{len(rows)} profiles written")
